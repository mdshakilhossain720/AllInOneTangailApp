    ('Nirala Super', false, 280),
    ('Dhaleshwari Paribahan', false, 250),
    ('Jhatika Deluxe', false, 300),
    ('Binimoy AC', true, 450),
    ('Shohag Paribahan', true, 550),
    ('Nirala Super', false, 280),
    ('Hanif Enterprise', true, 500),
    ('Desh Travels', true, 480),
    ('Dhaleshwari Paribahan', false, 250),
  ];
  const times = [
    ('06:00 AM', '08:45 AM'),
    ('06:30 AM', '09:15 AM'),
    ('07:15 AM', '10:00 AM'),
    ('08:00 AM', '10:30 AM'),
    ('09:30 AM', '12:00 PM'),
    ('11:00 AM', '01:45 PM'),
    ('02:00 PM', '04:30 PM'),
    ('04:30 PM', '07:00 PM'),
    ('07:00 PM', '09:45 PM'),
  ];
  return [
    for (var i = 0; i < ops.length; i++)
      BusTrip(
        id: 'bus$i',
        operator: ops[i].$1,
        from: from,
        to: to,
        depart: times[i].$1,
        arrive: times[i].$2,
        counter: i.isEven ? 'New Bus Stand Counter' : 'Nirala Mor Counter',
        fare: ops[i].$3,
        ac: ops[i].$2,
        seats: (i * 7 + 5) % 28 + 2,
      ),
  ];
}

