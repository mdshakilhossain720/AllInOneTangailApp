/// Demo prayer times for "today" (approximate for Tangail).
List<Prayer> prayersFor(DateTime day) {
  DateTime at(int h, int m) => DateTime(day.year, day.month, day.day, h, m);
  return [
    Prayer('fajr', at(4, 32)),
    Prayer('sunrise', at(5, 48)),
    Prayer('dhuhr', at(11, 52)),
    Prayer('asr', at(15, 58)),
    Prayer('maghrib', at(17, 41)),
    Prayer('isha', at(18, 56)),
  ];
}

/// Next of the five waqt (skips sunrise); rolls over to tomorrow's Fajr.
Prayer nextPrayer(DateTime now) {
  final today = prayersFor(now).where((p) => p.key != 'sunrise');
  for (final p in today) {
    if (p.time.isAfter(now)) return p;
  }
  return prayersFor(now.add(const Duration(days: 1))).first;
}

